#include <iostream>
#include <sstream>
#include <cmath>
#include <valarray>
#include <iomanip>

int main(int argc, char const *argv[]) {
  unsigned short n;
  unsigned int s;
  std::string Param;
  std::istringstream iss;

  while (true) {
    getline(std::cin, Param);
    iss.str(Param);
    iss >> n;
    iss.clear();
    if (n != 0) {
      std::valarray<double> si((double)0, n);
      getline(std::cin, Param);
      iss.str(Param);

      for (size_t i = 0; i < n; i++) {
        iss >> s;
        si[i] = s;
      }
      iss.clear();
      double m = si.sum() / n;
      double a = sqrt(pow(si - m, 2).sum() / n);
      std::cout << std::fixed << std::setprecision(8) << a << std::endl;
    } else {
      break;
    }
  }
  return 0;
}