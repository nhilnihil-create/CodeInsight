#include <cmath>
#include <iostream>
#include <string>
#include <vector>
#include <iomanip>

using std::cin;
using std::cout;
using std::endl;
using std::vector;

int main() {
	double N;
	double sum;
	vector<int> points;
	double sum_diff;

	while (true)
	{
		double ave;
		sum_diff = 0;
		sum = 0;
		N = 0;
		ave = 0;
		cin >> N;

		if (N == 0) break;

		// ????¨?????¨????
		for (size_t i = 0; i < N; i++)
		{
			int point;
			cin >> point;
			// ??????????????°???????????????
			points.push_back(point);
			sum += point;
		}

		// ??????
		ave = sum / N;

		// ????????¨??????????????\??????????????\??????
		for (size_t i = 0; i < points.size(); i++)
		{
			// ?????????????¨?????¨??????????
			sum_diff += pow((points[i] - ave), 2.0);
		}

		// ??????
		cout << std::fixed << std::setprecision(10)
			 << sqrt(sum_diff / N) << endl;
		points.clear();
	}
	return 0;
}