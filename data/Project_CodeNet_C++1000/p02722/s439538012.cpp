map< ll, ll > prime_factor(ll n) {
  map< ll, ll > ret;
  for(ll i = 2; i * i <= n; i++) {
    while(n % i == 0) {
      ret[i]++;
      n /= i;
    }
  }
  if(n != 1) ret[n] = 1;
  return ret;
}

vector< ll > divisor(ll n) {
  vector< ll > ret;
  for(ll i = 1; i * i <= n; i++) {
    if(n % i == 0) {
      ret.push_back(i);
      if(i * i != n) ret.push_back(n / i);
    }
  }
  sort(begin(ret), end(ret));
  return (ret);
}

int main() {
    ll N;
    cin >> N;

    ll ans_1 = 1, ans_2 = 0;
    // K: Nの約数じゃない
    map<ll, ll> factors1 = prime_factor(N-1);
    for(auto p = factors1.begin(); p != factors1.end(); ++p) {
        ans_1 *= (p->second + 1);
    }
    ans_1 -= 1;
    // cerr << "ans1 = " << ans_1 << endl;

    // K: Nの約数
    vector<ll> divs = divisor(N);
    for(ll d: divs) {
        if(d == 1) continue;
        ll n = N;
        while(n%d == 0) n = n / d;
        if((n-1)%d == 0) ans_2++;
    }

    cout << ans_1 + ans_2 << endl;
    return 0;
}