#define MOD 1000000007

const int MAX = 510000;

long long fac[MAX], finv[MAX], inv[MAX];

// テーブルを作る前処理
void COMinit() {
    fac[0] = fac[1] = 1;
    finv[0] = finv[1] = 1;
    inv[1] = 1;
    for (int i = 2; i < MAX; i++){
        fac[i] = fac[i - 1] * i % MOD;
        inv[i] = MOD - inv[MOD%i] * (MOD / i) % MOD;
        finv[i] = finv[i - 1] * inv[i] % MOD;
    }
}

// 二項係数計算
long long COM(int n, int k){
    if (n < k) return 0;
    if (n < 0 || k < 0) return 0;
    return fac[n] * (finv[k] * finv[n - k] % MOD) % MOD;
}
int main() {
    //cout << fixed << setprecision(8);
    
    int H = readInt(), W = readInt(), A = readInt(), B = readInt();
    
    COMinit();
    
    LL ans = 0;
    
    for(int i=0; i<H-A; ++i){
        ans += COM(i+B-1, i) * COM(H-(i+1)+W-(B+1), H-(i+1));
        ans %=MOD;
    }
    cout << ans << endl;
    
	return 0;
}