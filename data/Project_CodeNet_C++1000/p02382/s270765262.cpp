#include <iostream>
#include <sstream>
#include <valarray>
#include <iomanip>

int main(int argc, char const *argv[]) {
  std::string Param;
  std::istringstream iss;
  unsigned short n;
  double Manhattan, Euclidean, Chebyshev, D;

  getline(std::cin, Param);
  iss.str(Param);
  iss >> n;
  iss.clear();

  std::valarray<double> x((double)0, n);
  std::valarray<double> y((double)0, n);

  getline(std::cin, Param);
  iss.str(Param);
  for (size_t i = 0; i < n; i++) {
    int xi = 0;
    iss >> xi;
    x[i] = xi;
  }
  iss.clear();

  getline(std::cin, Param);
  iss.str(Param);
  for (size_t i = 0; i < n; i++) {
    int yi = 0;
    iss >> yi;
    y[i] = yi;
  }
  iss.clear();

  Manhattan = abs(x - y).sum();
  Euclidean = sqrt(pow(abs(x - y), 2).sum());
  D = cbrt(pow(abs(x - y), 3).sum());
  Chebyshev = abs(x - y).max();

  std::cout << std::fixed << std::setprecision(8);
  std::cout << Manhattan << std::endl;
  std::cout << Euclidean << std::endl;
  std::cout << D << std::endl;
  std::cout << Chebyshev << std::endl;

  return 0;
}