using namespace std;


int main(int argc, char** argv) {
    ios::sync_with_stdio(false);
    cin.tie(0);
    cout << fixed << setprecision(12);

    int n;
    cin >> n;
    vector<int> A(n);
    for (int i = 0; i < n; ++i) {
        cin >> A[i];
    }
    sort(A.begin(), A.end());

    int res = 0;
    for (int i = 0; i < n; ++i) {
        int cnt = 1;
        while (i + 1 < n && A[i] == A[i + 1]) {
            ++cnt;
            ++i;
        }
        res += cnt & 1;
    }

    cout << res << '\n';


    return 0;
}