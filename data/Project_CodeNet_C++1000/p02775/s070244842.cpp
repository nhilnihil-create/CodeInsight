#include <bits/stdc++.h>

using namespace std;
typedef long long ll;
typedef pair<double, int> PII;
const int N = 1000000 + 5;
const double eps = 1e-9;


int main() {
    string s;
    cin >> s;
    ll ans = 0;
    for (int i = s.length() - 1; i >= 0; i--) {
        if (s[i] > '5') {
            ans += '9' - s[i] + 1;
            if (i == 0)
                ans += 1;
            else if (s[i - 1] == '9') {
                int j = i - 1;
                while (j >= 0) {
                    if (s[j] == '9') {
                        s[j] = '0';
                        j--;
                    } else {
                        s[j] += 1;
                        break;
                    }
                }
                if (j < 0)
                    ans += 1;
            } else
                s[i - 1] += 1;
        } else if (s[i] == '5') {
            ans += '9' - s[i] + 1;
            if (i != 0 && s[i - 1] >= '5')
                s[i - 1] += 1;
        } else
            ans += s[i] - '0';
    }
    cout << ans << endl;
    return 0;
}