#include <bits/stdc++.h>
using namespace std;
int main(void){
    int n,f,Alice=0,Bob=0;
    cin>>n;
    vector<int> a(n);
    for(int i=0;i<n;i++){
        cin>>a.at(i);
    }
    sort(a.begin(),a.end());
    reverse(a.begin(),a.end());
    f=(n+1)/2;
    for(int i=0;i<f;i++){
        Alice+=a.at(i*2);
        if(i*2+1<=n-1)
        Bob+=a.at(i*2+1);
    }
    cout<<Alice-Bob<<endl;
}





















































































































































































































































































































































































































































































































































































































































































































































