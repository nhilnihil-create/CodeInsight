#include <bits/stdc++.h>
using namespace std;
#define MOD 1000000007

int main() {
    int N;
    cin >> N;

    int cnt=0;

    for(int i = 1; i <= N; i++){
        if(i / 10 == 0) cnt++;          //1 ~ 9
        else if(i / 100 == 0){          //10 ~ 99
            if(i / 10 == i % 10){   //11,22,33,...,99
                //i=11のとき (1, 11), (11, 1)
                cnt += 2;
                //(i, i)
                cnt++;
            }
            else if(i / 10 > i % 10 && i % 10 != 0){   //21,31,32,41,42,43,51,...,97,98
                //i=21のとき (12, 21), (21, 12)
                cnt += 2;
            }
        }
        else if(i / 1000 == 0){     //100 ~ 999
            if(i / 100 == i % 10){
                //i=292のとき (2, 292), (22, 292), (202, 292), (212, 292), ..., (282, 292) * 2!
                cnt += (2 + (i / 10 % 10)) * 2;
                cnt++;
            }
            else if(i / 100 < i % 10 && i % 10 != 0){
                //i=385のとき (53, 385), (385, 53)
                cnt += 2;
            }
            else if(i / 100 > i % 10 && i % 10 != 0){
                cnt += 11 * 2;
            }
        }
        else if(i / 10000 == 0){    //1000 ~ 9999
            if(i / 1000 == i % 10){
                cnt += (12 + (i / 10 % 100)) * 2;
                cnt++;
            }
            else if(i / 1000 < i % 10 && i % 10 != 0){
                cnt += 11 * 2;
            }
            else if(i / 1000 > i % 10 && i % 10 != 0){
                cnt += 111 * 2;
            }
        }
        else if(i / 100000 == 0){   //10000 ~ 99999
            if(i / 10000 == i % 10){
                cnt += (112 + (i / 10 % 1000)) * 2;
                cnt++;
            }
            else if(i / 10000 < i % 10 && i % 10 != 0){
                cnt += 111 * 2;
            }
            else if(i / 10000 > i % 10 && i % 10 != 0){
                cnt += 1111 * 2;
            }            
        }
        else{                       //100000 ~ 200000
            if(i / 100000 == i % 10){
                cnt += (1112 + (i / 10 % 10000)) * 2;
                cnt++;
            }
            else if(i / 100000 < i % 10 && i % 10 != 0){
                cnt += 1111 * 2;
            }
            else if(i / 100000 > i % 10 && i % 10 != 0){
                cnt += 11111 * 2;
            }             
        }
    }

        cout << cnt << endl;
}
