#include <iostream>
#include <string>
#include <cmath>
#include <vector>
#include <deque>

using namespace std;

#define rep(i, n) for (int i = 0; i < (int)(n); i++)
#define all(x) (x).begin(),(x).end()
#define ctoi(c) c - '0'
#define tos(s) to_string(s)

typedef long long ll;


int main() {
    deque<char> s;
    string ss;
    int q;
    cin >> ss >> q;
	for (auto i : ss) s.push_back(i);
    int t,f;
    char c;
    int l = 1;
    rep(i, q) {
        cin >> t;
        if (t == 1) {
            l *= -1;
        } else {
            cin >> f;
            cin >> c;
            if (f*l == 1 || f*l == -2) {
                s.push_front(c);
            } else {
                s.push_back(c);
            }
        }
    }
    if (l == -1) {
        reverse(all(s));
    }
    
    string ans;
    for (auto i : s) ans.push_back(i);
    cout << ans << endl;
    return 0;
}

