void MAIN() {
  int n, l;
  cin >> n >> l;
  int s = 0, m = 2e9;
  for (int i = 0; i < n; i++) {
    s += l + i;
    if (abs(m) > abs(l + i)) m = l + i;
  }
  cout << s - m << '\n';
}

