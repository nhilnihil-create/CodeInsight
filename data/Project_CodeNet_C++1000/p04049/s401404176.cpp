typedef vector<int> vec;
typedef vector<vector<int>> mat;

vec used;
mat edge;
int n,k;
void dfs(int no, int dist, vec &flag){
  used[no]++;
  if(dist > k/2) flag[no]++;
  for(int to : edge[no]){
    if(used[to]) continue;
    dfs(to,dist+1,flag);
  }
}

