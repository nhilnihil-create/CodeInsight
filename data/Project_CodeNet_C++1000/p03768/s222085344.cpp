const int N = 1e5+10;
vector<int> edge[N];
mat ans(N,vec(11,-1));

void dfs(int no, int dep, int col){
  if(ans[no][dep]!=-1) return;
  ans[no][dep] = col;
  for(int to: edge[no]){
    if(!dep) continue;
    dfs(to,dep-1,col);
  }
}

