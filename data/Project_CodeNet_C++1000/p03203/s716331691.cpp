  Left[0] = 0;
  for(ll i = 1; i < W; i++){
    Left[i] = Left[i-1] + 1;
    while(sho.count({i, Left[i]})){
      Left[i]++;
    }
  }
  ll ans = H;
  rep(i, N){
    if(X[i] >= Left[Y[i]]){
      ans = min(ans, X[i]);
    }
  }
