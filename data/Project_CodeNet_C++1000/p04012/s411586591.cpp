#include<stdio.h>
#include<ctype.h>
int main()
{
     char a[200];
     int i,j,k,s=1,q=0;
     for(i=0;i>=0;i++)
     {
         scanf("%c",&a[i]);
         if(isspace(a[i]))
         {
             break;
         }
     }
     for(j=0;j<i;j++)
     {
         for(k=0;k<i;k++)
         {
              if(a[k]>a[j])
              {
                   char tmp=a[j];
                   a[j]=a[k];
                   a[k]=tmp;
              }
         }
     }
     for(j=0;j<i-1;j++)
     {
         if(a[j]==a[j+1])
         {
             s++;
         }
         else
         {   
             if(s%2!=0)
             {
                 q++;
                 printf("No\n");
                 break;
             }
             else
             {
                 s=1;
             }
         }
     }
     if(q==0)
     {
     if(s%2==0)
     {
         printf("Yes\n");
     }
     else
     {
         printf("No\n");
     }
     }
     return 0;
}