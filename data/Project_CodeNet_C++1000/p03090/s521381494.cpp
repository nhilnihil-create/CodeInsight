void out(Head&& h,Tail&&... t){cout << h;vout(forward<Tail>(t)...);}

int main(){
	cin.tie(0);
	ios::sync_with_stdio(false);
	cout<<fixed<<setprecision(10);

	int N=in();
	int L=N%2?N:N+1;
	
	vector<pair<int,int>> P;
	REP(i,N){
		for(int j=i+1;j<N;j++){
			if(j+1+i+1==L) continue;
			P.emplace_back(i+1,j+1);
		}
	}
	out(P.size());
	for(auto& x:P) out(x.first,x.second);
	return 0;
}
