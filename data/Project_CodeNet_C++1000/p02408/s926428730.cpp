int C2int(char C)
{
  int out;
  if(C == 'S')
    out = 1;
  else if(C == 'H')
    out = 2;
  else if(C == 'C')
    out = 3;
  else if(C == 'D')
    out = 4;
  else{
    cout << "Error: undefined card type was typed";
    return 0;
  }

  return out;
}