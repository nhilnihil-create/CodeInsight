map< int64_t, int > prime_factor(int64_t n) {
  map< int64_t, int > ret;
  for(int64_t i = 2; i * i <= n; i++) {
    while(n % i == 0) {
      ret[i]++;
      n /= i;
    }
  }
  if(n != 1) ret[n] = 1;
  return ret;
}

int main() {
  int N; cin >> N;
  ll MOD = pow(10, 9) + 7;
  map<int64_t, int> m;
  for(int P = 1; P <= N; ++P) {
    for(auto x: prime_factor(P)) {
      while(x.second--) {
        m[x.first]++;
      }
    }
  }

  ll ans = 1;
  for(auto x: m) {
    ans *= (x.second + 1);
    ans = ans % MOD;
  }
  cout << ans << endl;
}
