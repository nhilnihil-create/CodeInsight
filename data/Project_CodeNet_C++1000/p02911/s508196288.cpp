class Stream{
public:
    Stream(){

    }
    //配列以外の入力を受け取る
    void read(){

    }
    template<typename First, typename... Rest>
    void read(First& first, Rest&... rest){
        cin >> first;
        read(rest...);
    }
    template<typename T>
    vector<T> read_vec(size_t n){
        vector<T> tmp(n);
        for(size_t i = 0; i < n; i++){
            cin >> tmp[i];
        }
        return tmp;
    }
    //配列を区切って出力する
    template<typename T>
    void write_vec(vector<T>& v, char divider){
        for(size_t i = 0; i < v.size(); i++){
            cout << v[i] << divider;
        }
    }
};

int main(){
    Stream io;

    int N, K, Q;
    io.read(N, K, Q);
    auto A = io.read_vec<int>(Q);

    vector<int> v(N, K - Q);

    for(int i = 0; i < Q; i++){
        v[A[i] - 1]++;
    }

    for(int i = 0; i < N; i++){
        string ans = "No";
        if(v[i] > 0) ans = "Yes";
        cout << ans << '\n';
    }
    return 0;
}