#include <iostream>
#include <string>
#include <cmath>
#include <vector>
#include <deque>

using namespace std;

#define rep(i, n) for (int i = 0; i < (int)(n); i++)
#define all(x) (x).begin(),(x).end()
#define ctoi(c) c - '0'
#define tos(s) to_string(s)

typedef long long ll;


int main() {
    ll n;
    cin >> n;
    ll a[n], b[n];
    rep(i,n) {
        cin >> a[i] >> b[i];
    }
    sort(a, a+n);
    sort(b, b+n);
    if (n%2==0) {
        cout << b[n/2-1]+b[n/2] - a[n/2-1]-a[n/2] + 1 << endl;
    } else {
        cout << b[(n+1)/2-1] - a[(n+1)/2-1] + 1 << endl;
    }
    return 0;
}

