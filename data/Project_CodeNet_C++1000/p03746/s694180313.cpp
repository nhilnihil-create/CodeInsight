constexpr int MAX_N = 100010;
vector<int> G[MAX_N];

int main() {

    int N, M;
    cin >> N >> M;

    vector<int> A(M), B(M);
    for (int i = 0; i < M; i++) {
        cin >> A[i] >> B[i];
        A[i]--;
        B[i]--;
        G[A[i]].push_back(B[i]);
        G[B[i]].push_back(A[i]);
    }

    deque<int> D;
    D.push_front(A[0]);
    D.push_back(B[0]);

    vector<bool> used(N, false);
    used[A[0]] = used[B[0]] = true;

    while (true) {
        bool new_find = false;

        int v1 = D.front();
        for (int i = 0; i < G[v1].size(); i++) {
            int to = G[v1][i];
            if (used[to]) continue;
            new_find = true;
            used[to] = true;
            D.push_front(to);
            break;
        }

        int v2 = D.back();
        for (int i = 0; i < G[v2].size(); i++) {
            int to = G[v2][i];
            if (used[to])continue;
            new_find = true;
            used[to] = true;
            D.push_back(to);
            break;
        }

        if (!new_find) break;
    }

    cout << D.size() << endl;
    for (auto x: D) cout << x + 1 << " ";

    return 0;
}














































