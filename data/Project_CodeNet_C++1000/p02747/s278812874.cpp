#include <bits/stdc++.h>
using namespace std;

int main() {
    string S;
    cin >> S;
    if(S == "hi") {
        cout << "Yes" << endl;
    } 
    else if(S == "hihi") {
        cout << "Yes" << endl;
    }
    else if(S == "hihihi") {
        cout << "Yes" << endl;
    }
    else if(S == "hihihihi" ) {
        cout << "Yes" << endl;
    }
    else if(S == "hihihihihi") {
        cout << "Yes" << endl;
    }  
    else {
        cout << "No" <<  endl;
    }
}
