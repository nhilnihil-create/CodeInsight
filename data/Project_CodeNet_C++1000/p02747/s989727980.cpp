#include<iostream>
#include<cstdio>
#include<cmath>
using namespace std;

int main()
{
	string h;
	cin >> h;
	if(h=="hi")
	{
		cout << "Yes" << endl;
	}else if(h=="hihi")
	{
		cout << "Yes" << endl;
	}else if(h=="hihihi")
	{
		cout << "Yes" << endl;
	}else if(h=="hihihihi")
	{
		cout << "Yes" << endl;
	}else if(h=="hihihihihi")
	{
		cout << "Yes" << endl;
	}else cout << "No" << endl;
	return 0;
}