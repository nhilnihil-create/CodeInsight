using ll = long long;
using pii = pair<int, int>;
using vi = V<int>;
using vii = V<pii>;
using vvi = VV<int>;
using mii = map<int, int>;
using umii = unordered_map<int, int>;
using si = set<int>;
using usi = unordered_set<int>;

int N;
vvi ans;

void solve(int st, int en, int dep) {
	if (st >= en)
		return;
	int mid = st + (en - st) / 2;
	db(st, en, mid);
	for (int i = st; i <= mid; ++i) {
		for (int j = mid + 1; j <= en; ++j) {
			ans[i][j] = dep;
		}
	}
	solve(st, mid, dep + 1);
	solve(mid + 1, en, dep + 1);
}

int main() {
	#ifdef LOCAL
	auto stTime = clock();
	#endif
//	freopen("in.txt", "r", stdin);
	ios::sync_with_stdio(false);
	cout.precision(10);
	cin.tie(0);

	cin >> N;
	ans.assign(N + 1, vi(N + 1));
	solve(1, N, 1);

	for (int i = 1; i <= N - 1; ++i) {
		for (int j = i + 1; j <= N; ++j) {
			cout << ans[i][j] << " \n"[j == N];
		}
	}

	#ifdef LOCAL
	cout << "\n\n\nExecution time: " <<
		(clock() - stTime) * 1e3 / CLOCKS_PER_SEC << " ms" << endl;
	#endif
    return 0;
}
