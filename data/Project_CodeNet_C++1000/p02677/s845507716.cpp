#include<iostream>
#include<vector>
#include<cmath>
#include<iomanip>
const double  pi = 3.1415926535897932384626;
using namespace std;
int main() {
    cout << fixed << setprecision(20);
    int a, b;
    double h, m;
    cin >> a >> b >> h >> m;
    h = ((int)h%12) * 30 + 0.5 * m;
    m = m*6;
    double O = pi * (double) (fabs(h - m)) / 180.0;
   cout << sqrt(a*a + b*b - 2*a*b*cos(O));
   // system("pause");
}

