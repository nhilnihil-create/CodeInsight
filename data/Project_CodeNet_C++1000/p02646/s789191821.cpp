#include <string>
#include <cmath>
#include <vector>
#include <deque>

using namespace std;

#define rep(i, n) for (int i = 0; i < (int)(n); i++)
#define all(x) (x).begin(),(x).end()
#define ctoi(c) c - '0'
#define tos(s) to_string(s)

typedef long long ll;


int main() {
    ll a,v,b,w,t;
    cin >> a >> v >> b >> w >> t;
    if (a == b) {
        cout << "YES" << endl;
    } else if (v > w && abs(a-b) <= (v - w)*t) {
        cout << "YES" << endl;
    } else {
        cout << "NO" << endl;
    }
    return 0;
}

