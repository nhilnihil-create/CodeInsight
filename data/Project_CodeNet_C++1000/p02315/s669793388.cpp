#include <iostream>
using namespace std;

int main(){
  int N,W;
  cin >> N >> W;
  int v[N],w[N];
  for(int i=1; i<=N; ++i){
    cin >> v[i] >> w[i];
  }

  int V[N+1][W+1] = {};
  for(int i=1; i<=N; ++i){
    V[i][0]=0; // c = w[i]?????´????????????
    for(int c=1; c<=W; ++c){
      V[0][c]=0; // i = 1?????´????????????
      // V[i-1][c-w[i]]?????????????????????????????????c<w[i]??§???i?????°????????????????????§????????????
      if(c-w[i] < 0){
        V[i][c] = V[i-1][c];
        continue;
      }
      V[i][c] = max(V[i-1][c-w[i]]+v[i],V[i-1][c]);
    }
  }

  int ans = 0;
  for(int c=0; c<=W; ++c){
    ans = max(ans, V[N][c]);
  }
  cout << ans << endl;
}