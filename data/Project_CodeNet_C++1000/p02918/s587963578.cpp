namespace solver {
  using namespace std;
  typedef long long ll;

  int N, K;
  string S;

  void init() {
    cin >> N >> K >> S;
  }

  void solve() {
    bool cur = true;
    int a = 0;
    rep(i, N) {
      if((cur && S[i] == 'L') || (!cur && S[i] == 'R')) {
        cur = !cur;
        if(!cur) {
          a += 2;
          if(i == 0) a--;
        }
      }
    }
    if(cur) a++;
    cout << min(N - 1, N - a + 2 * K) << "\n";
  }
}

int main() {
  std::ios::sync_with_stdio(false);
  std::cin.tie(0);
  solver::init();
  solver::solve();
  return 0;
}