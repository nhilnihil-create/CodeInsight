int dfs(int u)
{
  color[u] = 1;
  d[u] = ++tt; //????????????????¨????
  for (int i = 0; i < n; i++) {
    if (v[u][i] == 0) continue;
    if (color[i] == 0) {
      dfs(i);
    }
  }
  color[u] = 2;
  f[u] = ++tt; //?¨?????????????
}

signed main()
{
  int u, k;

  cin >> n;
  for (int i = 0; i < n; i++) {
    cin >> u >> k;
    u--;
    for (int j = 0; j < k; j++) {
      int tmp;
      cin >> tmp;
      tmp--;
      v[u][tmp] = 1;
    }

  }

  for (int u = 0; u < n; u++) {
    if (color[u] == 0) dfs(u);
  }

  for (int i = 0; i < n; i++) {
    cout << i + 1 << " " << d[i] << " " << f[i] << endl;
  }

  return (0);
}