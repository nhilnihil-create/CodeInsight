#define eb emplace_back
const int MOD=1e9+7;
const int INF=1e18;
const int MAX=3000;
int fac[MAX],finv[MAX],inv[MAX];
 
void COMinit(){
    fac[0]=fac[1]=1;
    finv[0]=finv[1]=1;
    inv[1]=1;
    for(int i=2;i<MAX;i++){
        fac[i]=fac[i-1]*i%MOD;
        inv[i]=MOD-inv[MOD%i]*(MOD/i)%MOD;
        finv[i]=finv[i-1]*inv[i]%MOD;
    }
}
 
int COM(int n,int k){
    if(n<k)return 0;
    if(n<0||k<0)return 0;
    return fac[n]*(finv[k]*finv[n-k]%MOD)%MOD;
}

signed main(){
    COMinit();
    int N,K;cin>>N>>K;
    REPS(i,K){
        cout<<COM(N-K+1,i)*COM(K-1,i-1)%MOD<<endl;
    }
}