const int NMAX = 1e5;
vec edge[NMAX], dist(NMAX,-1);
void dfs(int no){
  for(int to:edge[no]){
    if(dist[to] == -1){
      dist[to] = dist[no]+1;
      dfs(to);
    }
  }
}

int ans = 0;
int n,k;
vec a(NMAX);
int dfs2(int no){
  int mx = 0;
  for(int to:edge[no]){
    mx = max(mx,dfs2(to));
  }
  if(no == 0) return 0;
  if(mx == k-1 && a[no] != 1){
    ans++;
    return -1;
  }
  else return mx+1;
}

