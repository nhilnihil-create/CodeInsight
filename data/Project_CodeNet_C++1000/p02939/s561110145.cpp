const int N = 2e5+10;
int n;
char s[N];

int main(){
	scanf("%s",s+1),n=strlen(s+1);
	int ans=1,l=2,len=1;
	while (l<=n){
		if (len==2) l++,len=1,++ans;
		else if (s[l]==s[l-1]) l+=2,len=2,++ans;
		else l++,len=1,++ans;
	}
	if (l>n+1) ans--;
	printf("%d\n",ans);
}