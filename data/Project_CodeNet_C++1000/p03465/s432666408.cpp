const int N = 4e6;
bitset<N + 5> dp;

void hora(int tc) {
	int n;
	cin>>n;
	dp[0] = 1;
	int tot = 0;
	for(int i = 0;i < n;i++) {
		int x;
		cin>>x;
		dp |= (dp << x);
		tot += x;
	}
	for(int i = (tot + 1) / 2;i <= tot;i++) {
		if(dp[i] == 1) {
			cout<<i<<endl;
			return ;
		}
	}
}

