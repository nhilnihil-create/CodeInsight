const char newl = '\n';

int main() {
    int n,m;
    cin >> n >> m;
    string s;
    cin >> s;
    vector<int> a,ans;
    for (int i = 0;i < n+1;++i) if (s[i] == '0') a.push_back(i);
    int k = a.size()-1;
    bool ok = true;
    while (k) {
        int i = lower_bound(a.begin(),a.end(),a[k]-m)-a.begin();
        if (i == k) {
            ok = false;
            break;
        }
        ans.push_back(a[k]-a[i]);
        k = i;
    }
    if (ok) for (int i = ans.size()-1;i >= 0;--i) cout << ans[i] << " \n"[i == 0];
    else cout << -1 << newl;
}