vector<bool> prime(int n){
  vector<bool> is_prime(n, true);
  is_prime[0] = is_prime[1] = false;
  REP(i, n){
    if(!is_prime[i]) continue;
    for(int j = 2; i*j < n; j++){
      is_prime[i*j] = false;
    }
  }
  return is_prime;
}

