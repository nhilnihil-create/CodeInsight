void debug_out() { std::cerr << '\n'; }

template <class Head, class... Tail>
void debug_out(Head&& head, Tail&&... tail) {
  std::cerr << head;
  if (sizeof...(Tail) != 0) std::cerr << ", ";
  debug_out(std::forward<Tail>(tail)...);
}
using namespace std;
using int64 = long long;

int main() {
  int N;
  cin >> N;
  vector<int> a(N + 1);
  for (int i = 0; i < N; i++) {
    cin >> a[i + 1];
  }
  vector<int> ans(N + 1);
  for (int i = N; i >= 1; i--) {
    if (i * 2 > N) {
      ans[i] = a[i];
      continue;
    }
    int tmp = 0;
    for (int j = 2; i * j <= N; j++) {
      tmp += ans[i * j];
    }
    tmp %= 2;
    ans[i] = tmp ^ a[i];
  }
  debug(ans);
  cout << accumulate(ans.begin(), ans.end(), 0) << endl;
  for (int i = 1; i <= N; i++) {
    if (ans[i] == 1) {
      cout << i << ' ';
    }
  }
  cout << endl;
  return 0;
}