const number MAX = 100005;
number fac[MAX], finv[MAX], inv[MAX],Sum[MAX];
void COMinit() {
    fac[0] = fac[1] = 1;
    finv[0] = finv[1] = 1;
    inv[1] = 1;
    Sum[1] = 1;
    for (int i = 2; i < MAX; i++) {
        fac[i] = fac[i - 1] * i % MOD;
        inv[i] = MOD - inv[MOD % i] * (MOD / i) % MOD;
        finv[i] = finv[i - 1] * inv[i] % MOD;
        Sum[i] = (Sum[i-1] + inv[i]) % MOD;
    }
}

