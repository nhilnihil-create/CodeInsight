#include<iostream>
#include<algorithm>
#include<vector>
using namespace std;
const int N=2e5+2;
int ar[N];
vector<int> lis,lis1;
int main(){
	ios::sync_with_stdio(0);
	cin.tie(0);
	int n,i,j,k,l,ans=0;
	cin>>n;
	for(i=1;i<=n;i++){
		cin>>j;
		lis.push_back(j);
	}	
	for(j=30;j>=0;j--){
		if(!(j&1)){
			sort(lis.begin(),lis.end());
			lis1.clear();
			k=0;
			l=lis.size()-1;
			while(l>k){
				if(lis[k]+lis[l]==(1<<j)){
					ans++;
					k++;
					l--;
				}
				else{
					if(lis[k]+lis[l]>(1<<j)){
						lis1.push_back(lis[l]);
						l--;
					}
					else{
						lis1.push_back(lis[k]);
						k++;
					}
				}
			}
			if(l==k){
				lis1.push_back(lis[l]);
			}
		}
		else{
			sort(lis1.begin(),lis1.end());
			lis.clear();
			k=0;
			l=lis1.size()-1;
			while(l>k){
				if(lis1[k]+lis1[l]==(1<<j)){
					ans++;
					k++;
					l--;
				}
				else{
					if(lis1[k]+lis1[l]>(1<<j)){
						lis.push_back(lis1[l]);
						l--;
					}
					else{
						lis.push_back(lis1[k]);
						k++;
					}
				}
			}
			if(l==k){
				lis.push_back(lis1[l]);
			}
		}
	}
	cout<<ans;
}