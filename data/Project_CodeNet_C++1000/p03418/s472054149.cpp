int main()
{
	//freopen("input.txt", "r", stdin);
	//freopen("output.txt", "w", stdout);
	int n, k;
	cin >> n >> k;
	LL ans = 0;
	for (int i = k + 1; i <= n; i++)
	{
		ans += 1LL * n / i * (i - k) + max(0, n % i - k + 1);
	}
	if (k == 0) ans = 1LL * n * n;
	cout << ans << endl;
	return 0;
}
