int main()
{
	int n, k; cin >> n >> k;
	ll cnt = 0;
	for (int i = k + 1; i <= n; ++i)
	{
		cnt += (i - k)*(n / i);
		if (k == 0) cnt += (n%i) - k;
		else cnt += max(0, (n%i) - k + 1);

	}
	cout << cnt << endl;
}