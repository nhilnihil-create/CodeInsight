bool is_prime[MAX_SIZE];	//true:?´???°???false:?´???°??\???

//n??\???????´???°?????°????±???????
int sieve(int n){
	for(int i = 0;i <= n;i++)is_prime[i] = true;
	is_prime[0] = is_prime[1] = false;	//0??¨1????´???°??§?????????
	for(int i = 2;i <= n;i++){
		if(is_prime[i]){
			//n??\??????n?????°?????????false?????????
			for(int j = 2*i; j <= n;j+=i){
				is_prime[j] = false;
			}
		}
	}
}

//?????????a,?????????d???????????°??????n????????????????´???°????????????
int getNPrimeForProgression(int a,int d,int n){
	int c = 0,i = 1;
	while(c < n){
		if(is_prime[a+d*(i++-1)])c++;
	}
	i--;
	return a+d*(i-1);
}

