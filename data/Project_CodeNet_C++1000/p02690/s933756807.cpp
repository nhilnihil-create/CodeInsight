int main() {
  int64_t X;
  cin >> X;
  for (int i = -129; i < 129; i++) {
    for (int j = -128; j < 130; j++) {
      if (pow(i, 5) - pow(j, 5) == X) {
        cout << i << " " << j << endl;
        return 0;
      }
    }
  }
}
